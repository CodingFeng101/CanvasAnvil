/**
 * Copies what the PPT skill shares with the website into skill/ppt-skill:
 *
 *   - scripts/lib/website-prompts.mjs  the slide, edit, plan, template and beautify prompts and the retry rule,
 *                                      bundled from client/workspaces/ppt (one source for both)
 *   - prompts/plan-system.md, prompts/outline-edit.md, prompts/slide-edit-router.md   from resources/prompts/ppt
 *   - templates/*.jpg + templates/index.json  the website's preset template library
 *   - scripts/lib/mineru.mjs            MinerU figure extraction, bundled from server/routes/mineru.ts (with jszip)
 *   - scripts/vendor/pdf-lib.mjs, scripts/vendor/pptxgenjs.mjs  the export libraries, bundled so a copied skill needs no npm install
 *   - editable/render_preview.py       the LibreOffice preview renderer of the website's editable export
 *
 * Run after changing any of those on the website: node scripts/sync-ppt-skill.mjs
 */
import { copyFile, mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const skill = path.join(root, 'skill/ppt-skill');
const lib = path.join(root, 'client/workspaces/ppt');
const generated = '// Generated by scripts/sync-ppt-skill.mjs from client/workspaces/ppt -- do not edit here.\n';

const bundle = await build({
  stdin: {
    contents: [
      `export { buildPlanPrompt, buildPageImagePrompt, buildEditPagePrompt, buildStyleReferenceInstruction, buildChatImagesInstruction } from './lib/slide-prompts.ts';`,
      `export { getTemplateGenerationPrompt } from './lib/ppt-prompts.ts';`,
      `export { buildBeautifyInstruction } from './canvas/lib/beautify-instruction.ts';`,
      `export { isRetryableBeautifyError } from './canvas/lib/errors.ts';`,
    ].join('\n'),
    resolveDir: lib, loader: 'ts', sourcefile: 'website-prompts.ts',
  },
  bundle: true, platform: 'node', format: 'esm', target: 'node20', write: false, legalComments: 'none',
});
await writeFile(path.join(skill, 'scripts/lib/website-prompts.mjs'), generated + bundle.outputFiles[0].text);

await build({
  entryPoints: [path.join(root, 'server/routes/mineru.ts')], outfile: path.join(skill, 'scripts/lib/mineru.mjs'),
  bundle: true, platform: 'node', format: 'esm', target: 'node20', minify: true, legalComments: 'eof',
  banner: { js: `// Generated by scripts/sync-ppt-skill.mjs from server/routes/mineru.ts (jszip included) -- do not edit here.
import {createRequire as __createRequire} from "node:module";const require=__createRequire(import.meta.url);` },
});

await mkdir(path.join(skill, 'scripts/vendor'), { recursive: true });
for (const [name, contents] of [['pdf-lib', `export { PDFDocument } from 'pdf-lib';`], ['pptxgenjs', `export { default } from 'pptxgenjs';`]]) {
  await build({
    stdin: { contents, resolveDir: root, sourcefile: `${name}.js` }, outfile: path.join(skill, `scripts/vendor/${name}.mjs`),
    bundle: true, platform: 'node', format: 'esm', target: 'node20', minify: true, legalComments: 'eof',
    banner: { js: `// ${name}, bundled by scripts/sync-ppt-skill.mjs (licence at the end).
import {createRequire as __createRequire} from "node:module";const require=__createRequire(import.meta.url);` },
  });
}

for (const [from, to] of [['outline.md', 'plan-system.md'], ['outline-edit.md', 'outline-edit.md'], ['system.md', 'slide-edit-router.md']]) {
  const text = (await readFile(path.join(root, 'resources/prompts/ppt', from), 'utf8')).replace(/^﻿/, '');
  await writeFile(path.join(skill, 'prompts', to), `<!-- Generated by scripts/sync-ppt-skill.mjs from resources/prompts/ppt/${from} -- do not edit here. -->\n\n${text}`);
}

await copyFile(path.join(root, 'scripts/slide-agent/render_preview.py'), path.join(skill, 'editable/render_preview.py'));

// The template library: the presets the website's picker offers, full-size files only (no thumbnails).
const constants = await readFile(path.join(lib, 'canvas/lib/constants.ts'), 'utf8');
const field = (line, key) => line.match(new RegExp(`${key}: "([^"]*)"`))?.[1] ?? '';
const block = (name) => constants.slice(constants.indexOf(`export const ${name}`), constants.indexOf('];', constants.indexOf(`export const ${name}`)));
const categories = Object.fromEntries(block('TEMPLATE_CATEGORIES').split('\n').filter((l) => l.includes('id:'))
  .map((l) => [field(l, 'id'), { zh: field(l, 'zhName'), en: field(l, 'enName') }]));
const presets = block('PRESET_TEMPLATES').split('\n').filter((l) => l.includes('path:')).map((l) => ({
  id: field(l, 'id'), name: field(l, 'zhName'), enName: field(l, 'enName'),
  category: field(l, 'categoryId'), file: path.posix.basename(field(l, 'path')),
}));
const templates = path.join(skill, 'templates');
await rm(templates, { recursive: true, force: true });
await mkdir(templates, { recursive: true });
const available = new Set(await readdir(path.join(root, 'public/templates')));
const missing = presets.filter((p) => !available.has(p.file));
if (missing.length) throw new Error(`Template files missing: ${missing.map((p) => p.file).join(', ')}`);
for (const preset of presets) await copyFile(path.join(root, 'public/templates', preset.file), path.join(templates, preset.file));
const index = {
  note: 'Generated by scripts/sync-ppt-skill.mjs from the website template picker. Each file is a 16:9 template image: a style and colour-tone reference, not a layout.',
  categories: Object.entries(categories).filter(([id]) => presets.some((p) => p.category === id)).map(([id, name]) => ({ id, ...name })),
  templates: presets.map((p) => ({ ...p, categoryName: categories[p.category]?.zh ?? p.category })),
};
await writeFile(path.join(templates, 'index.json'), `${JSON.stringify(index, null, 2)}\n`);
console.log(`ppt-skill synced: prompts bundled, ${presets.length} templates in ${index.categories.length} categories`);
